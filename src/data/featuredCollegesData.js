export function getFeaturedColleges(category = "nirf") {
  if (category === "roi") {
    return FEATURED_COLLEGES
      .filter(c => c.feeNum && c.feeNum <= 15 && c.avgSalaryNum)
      .sort((a, b) => (b.avgSalaryNum / b.feeNum) - (a.avgSalaryNum / a.feeNum))
      .slice(0, 6);
  } else if (category === "metro") {
    return FEATURED_COLLEGES
      .filter(c => ["Delhi-NCR", "Mumbai", "Bengaluru", "Pune"].includes(c.city))
      .slice(0, 6);
  } else if (category === "iim") {
    return FEATURED_COLLEGES.filter(c => c.shortName?.startsWith("IIM ") || c.name.startsWith("IIM ")).slice(0, 6);
  } else {
    return FEATURED_COLLEGES
      .filter(c => c.nirfRank)
      .sort((a, b) => a.nirfRank - b.nirfRank)
      .slice(0, 6);
  }
}
